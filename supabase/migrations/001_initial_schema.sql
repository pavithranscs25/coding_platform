BEGIN;

CREATE TABLE IF NOT EXISTS public.profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT NOT NULL UNIQUE,
    email TEXT,
    avatar_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.problem_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('NOT_STARTED', 'ATTEMPTED', 'SOLVED')),
    first_attempted_at TIMESTAMPTZ,
    solved_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, problem_id)
);

CREATE TABLE IF NOT EXISTS public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL,
    language TEXT NOT NULL,
    code TEXT NOT NULL,
    status TEXT NOT NULL CHECK (
        status IN ('Accepted', 'Wrong Answer', 'Runtime Error', 'Compilation Error', 'Time Limit Exceeded')
    ),
    execution_time_ms INTEGER,
    memory_kb INTEGER,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_profiles_user_id
    ON public.profiles (user_id);

CREATE INDEX IF NOT EXISTS idx_profiles_username
    ON public.profiles (username);

CREATE INDEX IF NOT EXISTS idx_problem_progress_user_id
    ON public.problem_progress (user_id);

CREATE INDEX IF NOT EXISTS idx_problem_progress_problem_id
    ON public.problem_progress (problem_id);

CREATE INDEX IF NOT EXISTS idx_problem_progress_status
    ON public.problem_progress (status);

CREATE INDEX IF NOT EXISTS idx_problem_progress_user_problem
    ON public.problem_progress (user_id, problem_id);

CREATE INDEX IF NOT EXISTS idx_submissions_user_id
    ON public.submissions (user_id);

CREATE INDEX IF NOT EXISTS idx_submissions_problem_id
    ON public.submissions (problem_id);

CREATE INDEX IF NOT EXISTS idx_submissions_submitted_at
    ON public.submissions (submitted_at DESC);

CREATE INDEX IF NOT EXISTS idx_submissions_user_problem
    ON public.submissions (user_id, problem_id, submitted_at DESC);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql
SET search_path = public, pg_catalog;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    meta JSONB := COALESCE(NEW.raw_user_meta_data, '{}'::JSONB);
    base_username TEXT;
    safe_username TEXT;
BEGIN
    base_username := COALESCE(
        NULLIF(TRIM(meta->>'username'), ''),
        NULLIF(TRIM(meta->>'full_name'), ''),
        NULLIF(SPLIT_PART(COALESCE(NEW.email, ''), '@', 1), ''),
        'user_' || SUBSTRING(MD5(NEW.id::TEXT), 1, 12)
    );

    safe_username := lower(
        regexp_replace(
            regexp_replace(base_username, '[^a-zA-Z0-9._-]+', '_', 'g'),
            '^_+|_+$',
            '',
            'g'
        )
    );

    IF safe_username IS NULL OR safe_username = '' THEN
        safe_username := 'user_' || SUBSTRING(MD5(NEW.id::TEXT), 1, 12);
    ELSIF length(safe_username) < 3 THEN
        safe_username := safe_username || '_' || SUBSTRING(MD5(NEW.id::TEXT), 1, 6);
    END IF;

    IF EXISTS (SELECT 1 FROM public.profiles WHERE username = safe_username) THEN
        safe_username := safe_username || '_' || SUBSTRING(MD5(NEW.id::TEXT), 1, 8);
    END IF;

    INSERT INTO public.profiles (user_id, username, email, avatar_url)
    VALUES (
        NEW.id,
        safe_username,
        NEW.email,
        meta->>'avatar_url'
    )
    ON CONFLICT (user_id) DO NOTHING;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog;

CREATE TRIGGER set_profiles_updated_at
BEFORE UPDATE ON public.profiles
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER set_problem_progress_updated_at
BEFORE UPDATE ON public.problem_progress
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.problem_progress ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "profiles_select_own"
    ON public.profiles
    FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "profiles_insert_own"
    ON public.profiles
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "profiles_update_own"
    ON public.profiles
    FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "problem_progress_select_own"
    ON public.problem_progress
    FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "problem_progress_insert_own"
    ON public.problem_progress
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "problem_progress_update_own"
    ON public.problem_progress
    FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "submissions_select_own"
    ON public.submissions
    FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "submissions_insert_own"
    ON public.submissions
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

COMMIT;
